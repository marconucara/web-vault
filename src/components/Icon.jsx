function Svg({ content, color = 'currentColor', size }) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color || 'currentColor'}
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {content}
    </svg>
  );
}

export default function Icon({ name, color = 'currentColor', size = 16 }) {
  // 1) App UI icons (local set, takes precedence over lucide names).
  if (name && PATHS[name]) {
    return <Svg content={PATHS[name]} color={color} size={size} />;
  }
  // 2) Any valid lucide name (typical of Type icons): lazy-load the icon by
  //    name. While the chunk loads we render an invisible, size-preserving
  //    placeholder (no fallback icon) so there is no icon switch; the real
  //    icon then fades in on mount.
  if (name && LUCIDE_NAMES.has(name)) {
    return (
      <DynamicIcon
        name={name}
        size={size}
        strokeWidth={2}
        color={color || 'currentColor'}
        className="icon icon-fade-in"
        fallback={() => (
          <span
            className="icon icon-placeholder"
            style={{ display: 'inline-block', width: size, height: size }}
            aria-hidden="true"
          />
        )}
      />
    );
  }
  // 3) No name or unknown name: file-text fallback.
  return <Svg content={PATHS['file-text']} color={color} size={size} />;
}
